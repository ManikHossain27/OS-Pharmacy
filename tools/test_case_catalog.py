"""Single source of truth for the manual test-case suite and its execution status.

`build_excel_report.py` turns this into PMS_Product_Module_Test_Report.xlsx.
Update the ``status`` / ``actual`` fields here as cases are (re-)executed.

Status vocabulary
-----------------
Pass     - executed, behaved as expected
Fail     - executed, defect observed (see Bug ID)
Blocked  - could not execute because the feature's entry point is broken
           (chiefly BUG-PROD-002: the Add-Product [+] add-Company/Generic buttons)
N/A      - the scenario does not apply to this build (feature/field absent)
Not Run  - designed, not yet executed (e.g. the Barcode Generator module, and
           many field-level boundary permutations)

The 2026-09-08 live run results are layered on the design catalog via OVERRIDES
near the bottom of this file.  The earlier "AntD Select blocker" was a false
alarm - see docs/QA_TASK_REPORT.md section 7.
"""
from __future__ import annotations

from dataclasses import dataclass

PRECOND_DEFAULT = "Logged in as pms_tc11@gmail.com; Manik Pharma selected and verified in the sidebar"
ENV = "Staging"

COLUMNS = [
    "Test Case ID", "Module", "Feature", "Sub Feature", "Test Scenario",
    "Test Case Description", "Preconditions", "Test Data", "Reproducing Steps",
    "Expected Result", "Actual Result", "Status", "Test Type", "Priority",
    "Severity", "Environment", "Evidence", "Bug ID", "Remarks",
]


@dataclass
class TC:
    id: str
    module: str
    feature: str
    sub: str
    scenario: str
    desc: str
    steps: str
    expected: str
    ttype: str = "Positive"
    priority: str = "Medium"
    severity: str = ""
    status: str = "Not Run"
    actual: str = ""
    data: str = "-"
    precond: str = PRECOND_DEFAULT
    evidence: str = ""
    bug: str = ""
    remarks: str = ""

    def row(self) -> dict:
        return {
            "Test Case ID": self.id,
            "Module": self.module,
            "Feature": self.feature,
            "Sub Feature": self.sub,
            "Test Scenario": self.scenario,
            "Test Case Description": self.desc,
            "Preconditions": self.precond,
            "Test Data": self.data,
            "Reproducing Steps": self.steps,
            "Expected Result": self.expected,
            "Actual Result": self.actual,
            "Status": self.status,
            "Test Type": self.ttype,
            "Priority": self.priority,
            "Severity": self.severity,
            "Environment": ENV,
            "Evidence": self.evidence,
            "Bug ID": self.bug,
            "Remarks": self.remarks,
        }


CASES: list[TC] = []


def add(*cases: TC) -> None:
    CASES.extend(cases)


